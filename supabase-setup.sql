create table if not exists public.staff_profiles (
    user_id uuid primary key references auth.users(id) on delete cascade,
    full_name text not null,
    role text not null check (role in ('cashier', 'kitchen', 'admin')),
    created_at timestamptz not null default now()
);

create table if not exists public.orders (
    id bigint generated by default as identity primary key,
    buyer_name text not null,
    phone text not null default '',
    order_type text not null check (order_type in ('takeaway', 'delivery', 'dine-in')),
    address text not null default '',
    table_number text not null default '',
    payment_method text not null check (payment_method in ('Tunai', 'QRIS', 'Transfer bank')),
    payment_status text not null check (payment_status in ('Belum dibayar', 'Lunas')),
    cash_received bigint,
    change_due bigint,
    subtotal bigint not null check (subtotal >= 0),
    service_fee bigint not null check (service_fee >= 0),
    delivery_fee bigint not null check (delivery_fee >= 0),
    discount bigint not null check (discount >= 0),
    total bigint not null check (total >= 0),
    status text not null default 'Menunggu'
        check (status in ('Menunggu', 'Diproses', 'Selesai', 'Dibatalkan')),
    created_at timestamptz not null default now()
);

create table if not exists public.order_items (
    id bigint generated by default as identity primary key,
    order_id bigint not null references public.orders(id) on delete cascade,
    menu_id integer not null references public.menu_items(id),
    item_name text not null,
    unit_price bigint not null check (unit_price >= 0),
    quantity integer not null check (quantity > 0)
);

alter table public.menu_items enable row level security;
alter table public.staff_profiles enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

revoke all on public.menu_items, public.staff_profiles, public.orders, public.order_items
    from anon, authenticated;
grant select on public.menu_items to anon, authenticated;
grant select on public.staff_profiles, public.orders, public.order_items to authenticated;

create or replace function public.has_staff_role(p_roles text[])
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
    select exists (
        select 1
        from public.staff_profiles
        where user_id = auth.uid()
          and role = any (p_roles)
    );
$$;

revoke all on function public.has_staff_role(text[]) from public, anon;
grant execute on function public.has_staff_role(text[]) to authenticated;

drop policy if exists "Menu is public" on public.menu_items;
create policy "Menu is public"
    on public.menu_items for select
    to anon, authenticated
    using (true);

drop policy if exists "Staff can read own profile" on public.staff_profiles;
create policy "Staff can read own profile"
    on public.staff_profiles for select
    to authenticated
    using (user_id = auth.uid());

drop policy if exists "Staff can read orders" on public.orders;
create policy "Staff can read orders"
    on public.orders for select
    to authenticated
    using (public.has_staff_role(array['cashier', 'kitchen', 'admin']));

drop policy if exists "Staff can read order items" on public.order_items;
create policy "Staff can read order items"
    on public.order_items for select
    to authenticated
    using (public.has_staff_role(array['cashier', 'kitchen', 'admin']));

create or replace function public.place_order(p_order jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_buyer text;
    v_phone text;
    v_order_type text;
    v_address text;
    v_table_number text;
    v_payment_method text;
    v_cash_received bigint;
    v_discount_percent numeric;
    v_subtotal bigint := 0;
    v_service_fee bigint;
    v_delivery_fee bigint := 0;
    v_discount bigint;
    v_total bigint;
    v_payment_status text;
    v_entry record;
    v_menu public.menu_items%rowtype;
    v_order public.orders%rowtype;
    v_items jsonb := '[]'::jsonb;
begin
    if jsonb_typeof(p_order) is distinct from 'object' then
        raise exception 'Data pesanan tidak valid.';
    end if;

    v_buyer := trim(coalesce(p_order->>'buyer_name', ''));
    v_phone := trim(coalesce(p_order->>'phone', ''));
    v_order_type := p_order->>'order_type';
    v_address := trim(coalesce(p_order->>'address', ''));
    v_table_number := trim(coalesce(p_order->>'table_number', ''));
    v_payment_method := p_order->>'payment_method';

    if v_buyer = '' then
        raise exception 'Nama pembeli wajib diisi.';
    end if;
    if v_order_type is null or v_order_type not in ('takeaway', 'delivery', 'dine-in') then
        raise exception 'Jenis pesanan tidak valid.';
    end if;
    if v_payment_method is null or v_payment_method not in ('Tunai', 'QRIS', 'Transfer bank') then
        raise exception 'Metode pembayaran tidak valid.';
    end if;
    if v_order_type = 'delivery' and (v_phone = '' or v_address = '') then
        raise exception 'Nomor telepon dan alamat wajib diisi untuk pesan antar.';
    end if;
    if v_order_type = 'dine-in' and v_table_number = '' then
        raise exception 'Nomor meja wajib diisi untuk makan di tempat.';
    end if;
    if jsonb_typeof(p_order->'items') is distinct from 'array' then
        raise exception 'Keranjang pesanan kosong.';
    end if;
    if jsonb_array_length(p_order->'items') = 0 then
        raise exception 'Keranjang pesanan kosong.';
    end if;
    if exists (
        select 1
        from jsonb_array_elements(p_order->'items') as entry(value)
        where coalesce(entry.value->>'id', '') !~ '^[0-9]+$'
           or coalesce(entry.value->>'qty', '') !~ '^[1-9][0-9]*$'
    ) then
        raise exception 'Jumlah atau menu dalam pesanan tidak valid.';
    end if;
    if coalesce(p_order->>'discount_percent', '0') !~ '^[0-9]+(\.[0-9]+)?$' then
        raise exception 'Diskon tidak valid.';
    end if;

    v_discount_percent := least(
        100,
        greatest(0, coalesce((p_order->>'discount_percent')::numeric, 0))
    );

    for v_entry in
        select
            (entry.value->>'id')::integer as menu_id,
            sum((entry.value->>'qty')::integer)::integer as quantity
        from jsonb_array_elements(p_order->'items') as entry(value)
        group by (entry.value->>'id')::integer
        order by (entry.value->>'id')::integer
    loop
        select *
        into v_menu
        from public.menu_items
        where id = v_entry.menu_id
        for update;

        if not found then
            raise exception 'Menu tidak ditemukan.';
        end if;
        if v_menu.stock < v_entry.quantity then
            raise exception 'Stok % tersisa %; pesanan tidak disimpan.',
                v_menu.name, v_menu.stock;
        end if;

        update public.menu_items
        set stock = stock - v_entry.quantity,
            updated_at = now()
        where id = v_menu.id;

        v_subtotal := v_subtotal + v_menu.price * v_entry.quantity;
        v_items := v_items || jsonb_build_array(jsonb_build_object(
            'id', v_menu.id,
            'name', v_menu.name,
            'price', v_menu.price,
            'qty', v_entry.quantity
        ));
    end loop;

    v_service_fee := round(v_subtotal * 0.05);
    if v_order_type = 'delivery' then
        v_delivery_fee := 8000;
    end if;
    v_discount := round(v_subtotal * v_discount_percent / 100);
    v_total := greatest(0, v_subtotal + v_service_fee + v_delivery_fee - v_discount);

    v_cash_received := null;
    if v_payment_method = 'Tunai' then
        if coalesce(p_order->>'cash_received', '') !~ '^[0-9]+$' then
            raise exception 'Nominal uang tunai tidak valid.';
        end if;
        v_cash_received := (p_order->>'cash_received')::bigint;
        if v_cash_received < v_total then
            raise exception 'Uang tunai yang diterima belum mencukupi.';
        end if;
        v_payment_status := 'Lunas';
    else
        v_payment_status := 'Belum dibayar';
    end if;

    insert into public.orders (
        buyer_name, phone, order_type, address, table_number,
        payment_method, payment_status, cash_received, change_due,
        subtotal, service_fee, delivery_fee, discount, total
    )
    values (
        v_buyer, v_phone, v_order_type, v_address, v_table_number,
        v_payment_method, v_payment_status, v_cash_received,
        case when v_cash_received is null then null else v_cash_received - v_total end,
        v_subtotal, v_service_fee, v_delivery_fee, v_discount, v_total
    )
    returning * into v_order;

    insert into public.order_items (order_id, menu_id, item_name, unit_price, quantity)
    select v_order.id, item.id, item.name, item.price, item.qty
    from jsonb_to_recordset(v_items) as item(
        id integer,
        name text,
        price bigint,
        qty integer
    );

    return jsonb_build_object(
        'id', v_order.id,
        'buyer', v_order.buyer_name,
        'phone', v_order.phone,
        'orderType', v_order.order_type,
        'address', v_order.address,
        'tableNumber', v_order.table_number,
        'paymentMethod', v_order.payment_method,
        'paymentStatus', v_order.payment_status,
        'cashReceived', v_order.cash_received,
        'change', v_order.change_due,
        'items', v_items,
        'subtotal', v_order.subtotal,
        'fee', v_order.service_fee,
        'deliveryFee', v_order.delivery_fee,
        'discount', v_order.discount,
        'total', v_order.total,
        'status', v_order.status,
        'date', to_char(v_order.created_at at time zone 'Asia/Jakarta', 'DD/MM/YYYY, HH24:MI:SS')
    );
end;
$$;

create or replace function public.set_order_status(p_order_id bigint, p_status text)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_current_status text;
begin
    if not public.has_staff_role(array['cashier', 'kitchen', 'admin']) then
        raise exception 'Akun ini tidak memiliki akses antrean.';
    end if;
    if p_status is null or p_status not in ('Menunggu', 'Diproses', 'Selesai', 'Dibatalkan') then
        raise exception 'Status pesanan tidak valid.';
    end if;

    select status
    into v_current_status
    from public.orders
    where id = p_order_id
    for update;
    if not found then
        raise exception 'Pesanan tidak ditemukan.';
    end if;
    if v_current_status = 'Dibatalkan' and p_status <> 'Dibatalkan' then
        raise exception 'Pesanan yang dibatalkan tidak dapat dibuka kembali.';
    end if;
    if v_current_status = 'Selesai' and p_status = 'Dibatalkan' then
        raise exception 'Pesanan yang sudah selesai tidak dapat dibatalkan.';
    end if;

    if v_current_status <> 'Dibatalkan' and p_status = 'Dibatalkan' then
        update public.menu_items as menu
        set stock = menu.stock + cancelled_items.quantity,
            updated_at = now()
        from (
            select menu_id, sum(quantity)::integer as quantity
            from public.order_items
            where order_id = p_order_id
            group by menu_id
        ) as cancelled_items
        where menu.id = cancelled_items.menu_id;
    end if;

    update public.orders
    set status = p_status
    where id = p_order_id;

    return p_status;
end;
$$;

create or replace function public.set_payment_status(p_order_id bigint, p_status text)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if not public.has_staff_role(array['cashier', 'admin']) then
        raise exception 'Hanya kasir atau admin yang dapat mengubah status pembayaran.';
    end if;
    if p_status is null or p_status not in ('Belum dibayar', 'Lunas') then
        raise exception 'Status pembayaran tidak valid.';
    end if;

    update public.orders
    set payment_status = p_status
    where id = p_order_id;
    if not found then
        raise exception 'Pesanan tidak ditemukan.';
    end if;

    return p_status;
end;
$$;

create or replace function public.set_menu_stock(p_menu_id integer, p_stock integer)
returns integer
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if not public.has_staff_role(array['cashier', 'admin']) then
        raise exception 'Hanya kasir atau admin yang dapat mengubah stok.';
    end if;
    if p_stock is null or p_stock < 0 then
        raise exception 'Stok tidak boleh kurang dari nol.';
    end if;

    update public.menu_items
    set stock = p_stock,
        updated_at = now()
    where id = p_menu_id;
    if not found then
        raise exception 'Menu tidak ditemukan.';
    end if;

    return p_stock;
end;
$$;

